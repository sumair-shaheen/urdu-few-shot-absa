import pandas

"""
TF-IDF + Logistic Regression classical baseline for Urdu ABSA.

Reproduces the same experimental protocol used for the transformer
baselines in the thesis (Section 3.6/3.7, Section 4.5.1):
  - same fixed test set for every evaluation
  - same nested 5/10/20-shot support pools
  - same 3 seeds (42, 123, 2024)
  - reports mean +/- std accuracy and macro-F1 per shot setting

USAGE
-----
1. Fill in the file paths in the CONFIG section below.
2. Each support-set file should contain the labeled examples for ONE
   (seed, shot) combination -- e.g. one file for seed=42, shot=5,
   containing exactly the same rows used to fine-tune mBERT/XLM-R/mT5
   for that (seed, shot) pair. If your pipeline instead has ONE big
   file with seed/shot columns, see load_support_set() below --
   swap in a filter on that dataframe instead of read_csv per file.
3. The test set file should be the single fixed test set (1,689 rows)
   used throughout Chapter 4.

Expected columns in every CSV: Sentence, Aspect, domain, and a
sentiment label column (default name: "Sentiment" -- change
LABEL_COL below if yours is named "true_label" or similar).
"""

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score

# ----------------------------- CONFIG -----------------------------

# If running in Colab, mount Drive first:
#   from google.colab import drive
#   drive.mount('/content/drive')
BASE_PATH = "/content/drive/MyDrive/urdu_absa_project/data/splits"

TEST_SET_PATH = f"{BASE_PATH}/test.csv"
LABEL_COL = "Sentiment"                  # <-- change if your column is named differently (see auto-check in main())
SEEDS = [42, 123, 2024]
SHOTS = [5, 10, 20]


def support_set_path(seed: int, shot: int) -> str:
    return f"{BASE_PATH}/fewshot/seed{seed}/shot{shot}.csv"

# --------------------------------------------------------------------


def build_text(df: pd.DataFrame) -> pd.Series:
    """
    Combine sentence and aspect into a single input string for TF-IDF.
    This mirrors the standard ABSA framing (sentiment toward a specific
    aspect), by giving the aspect term explicit visibility in the
    feature space rather than relying on TF-IDF over the sentence alone.
    Adjust this if your ChatGPT run (or your intended design) combined
    the fields differently -- the exact wording of this line changes
    the numbers.
    """
    return df["Aspect"].astype(str) + " [ASPECT] " + df["Sentence"].astype(str)


def run_one_condition(seed: int, shot: int, test_df: pd.DataFrame) -> dict:
    train_df = pd.read_csv(support_set_path(seed, shot))

    X_train_text = build_text(train_df)
    y_train = train_df[LABEL_COL]

    X_test_text = build_text(test_df)
    y_test = test_df[LABEL_COL]

    vectorizer = TfidfVectorizer(
        max_features=5000,
        ngram_range=(1, 2),
        sublinear_tf=True,
    )
    X_train = vectorizer.fit_transform(X_train_text)
    X_test = vectorizer.transform(X_test_text)

    clf = LogisticRegression(
        max_iter=1000,
        random_state=seed,
        class_weight=None,  # thesis test set is class-balanced by construction
    )
    clf.fit(X_train, y_train)
    preds = clf.predict(X_test)

    return {
        "seed": seed,
        "shot": shot,
        "accuracy": accuracy_score(y_test, preds),
        "macro_f1": f1_score(y_test, preds, average="macro"),
        "n_train": len(train_df),
        "n_test": len(test_df),
    }


def main():
    global LABEL_COL
    test_df = pd.read_csv(TEST_SET_PATH)

    print("Columns found in test.csv:", list(test_df.columns))
    if LABEL_COL not in test_df.columns:
        # Try a few common alternatives before giving up, so a naming
        # mismatch doesn't just crash with a raw KeyError.
        candidates = ["Sentiment", "sentiment", "label", "true_label", "Label"]
        found = next((c for c in candidates if c in test_df.columns), None)
        if found is None:
            raise ValueError(
                f"Could not find a label column. Set LABEL_COL to one of: "
                f"{list(test_df.columns)}"
            )
        print(f"NOTE: LABEL_COL='{LABEL_COL}' not found; using '{found}' instead.")
        LABEL_COL = found

    rows = []
    for shot in SHOTS:
        for seed in SEEDS:
            result = run_one_condition(seed, shot, test_df)
            rows.append(result)
            print(
                f"shot={shot:2d}  seed={seed:5d}  "
                f"acc={result['accuracy']:.4f}  f1={result['macro_f1']:.4f}  "
                f"(train n={result['n_train']}, test n={result['n_test']})"
            )

    results_df = pd.DataFrame(rows)

    print("\n=== Summary (mean +/- std across 3 seeds) ===")
    summary = (
        results_df.groupby("shot")[["accuracy", "macro_f1"]]
        .agg(["mean", "std"])
    )
    print(summary)

    results_df.to_csv("tfidf_lr_baseline_results.csv", index=False)
    summary.to_csv("tfidf_lr_baseline_summary.csv")
    print(
        "\nSaved per-run results to tfidf_lr_baseline_results.csv "
        "and the summary table to tfidf_lr_baseline_summary.csv"
    )


if __name__ == "__main__":
    main()